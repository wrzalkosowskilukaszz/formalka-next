// Applies each fault in tools/mutations.mjs alone, runs the tests and restores the file. Writes
// eval/MUTATIONS.md. Exits 1 if any fault survives or doesn't apply. Usage: npm run mutate
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { MUTATIONS } from "./mutations.mjs";

const pkg = join(dirname(fileURLToPath(import.meta.url)), "..");
const originals = new Map();
const restore = () => { for (const [f, text] of originals) writeFileSync(f, text); };
process.on("SIGINT", () => { restore(); process.exit(130); });

const rows = [];
try {
  for (const m of MUTATIONS) {
    const file = join(pkg, m.file);
    const text = originals.get(file) ?? readFileSync(file, "utf8");
    originals.set(file, text);
    const count = text.split(m.find).length - 1;
    if (count !== 1) { rows.push({ ...m, result: `NOT APPLIED (found ${count}×)` }); continue; }
    writeFileSync(file, text.replace(m.find, m.replace));
    const run = spawnSync(process.execPath, ["--test", "--test-reporter=tap", "test/*.test.ts"], { cwd: pkg, encoding: "utf8" });
    writeFileSync(file, text);
    const failed = (/^# fail (\d+)/m.exec(run.stdout)?.[1]) ?? "?";
    rows.push({ ...m, result: run.status !== 0 ? `caught (${failed} failing)` : "SURVIVED" });
    process.stdout.write(run.status !== 0 ? "." : "S");
  }
} finally {
  restore();
}
const caught = rows.filter((r) => r.result.startsWith("caught")).length;
const report = [
  "# Mutation report", "",
  `Generated by \`npm run mutate\` (tools/mutate.mjs). Each fault is applied alone, the whole test suite runs, and the file is restored. ${caught} of ${rows.length} faults caught.`, "",
  "| Fault | What it breaks | File | Result |", "|---|---|---|---|",
  ...rows.map((r) => `| ${r.id} | ${r.what} | ${r.file} | ${r.result} |`), "",
].join("\n");
writeFileSync(join(pkg, "eval", "MUTATIONS.md"), report);
console.log(`\n${caught}/${rows.length} faults caught`);
for (const r of rows.filter((x) => !x.result.startsWith("caught"))) console.log(`  ${r.id}: ${r.result}`);
process.exit(caught === rows.length ? 0 : 1);
