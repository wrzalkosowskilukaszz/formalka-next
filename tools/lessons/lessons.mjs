// Lessons from mistakes, in three layers (docs/solutions/README.md):
//   1. one file per solved problem in docs/solutions/, with a one-line rule and the files it concerns;
//   2. an index of the rules, one line each (docs/solutions/INDEX.md), never loaded at session start;
//   3. a slice: only the rules whose files match the work at hand, to paste into the task's prompt.
// No dependencies; the frontmatter is a small YAML subset (key: value, key: [a, b]).
import { readFileSync, readdirSync, existsSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const DIR = join(ROOT, 'docs', 'solutions');
export const INDEX = join(DIR, 'INDEX.md');
export const INDEX_LIMIT = 12000; // characters; past it, merge similar lessons or archive old ones
const KINDS = ['content-safety', 'legal-source', 'engine', 'reader', 'ui-design', 'accessibility', 'testing', 'evidence-wording', 'tooling', 'process'];

export function parse(text, file = '') {
  const m = /^---\n([\s\S]*?)\n---\n?([\s\S]*)$/.exec(text);
  if (!m) throw new Error(`${file}: no frontmatter`);
  const meta = {};
  for (const line of m[1].split('\n')) {
    const kv = /^([a-z]+):\s*(.*)$/.exec(line);
    if (!kv) continue;
    const [, k, v] = kv;
    meta[k] = v.startsWith('[') ? v.slice(1, -1).split(',').map((x) => x.trim()).filter(Boolean) : v.trim();
  }
  for (const k of ['rule', 'kind', 'files', 'check', 'date']) if (!meta[k] || (Array.isArray(meta[k]) && !meta[k].length)) throw new Error(`${file}: missing "${k}"`);
  if (!KINDS.includes(meta.kind)) throw new Error(`${file}: kind "${meta.kind}" is not one of ${KINDS.join(', ')}`);
  if (!Array.isArray(meta.files)) meta.files = [meta.files];
  if (meta.rule.length > 220) throw new Error(`${file}: the rule is longer than one line (220 characters)`);
  return { ...meta, body: m[2] };
}

export function load(dir = DIR) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).filter((f) => /^\d{4}-\d{2}-\d{2}-.+\.md$/.test(f)).sort()
    .map((f) => ({ ...parse(readFileSync(join(dir, f), 'utf8'), f), path: relative(ROOT, join(dir, f)) }));
}

// "**" any depth, "*" within one folder, "?" one character.
export function globRe(glob) {
  let re = '';
  for (let i = 0; i < glob.length; i++) {
    const ch = glob[i];
    if (ch === '*' && glob[i + 1] === '*') { re += '.*'; i++; if (glob[i + 1] === '/') i++; }
    else if (ch === '*') re += '[^/]*';
    else if (ch === '?') re += '[^/]';
    else re += ch.replace(/[.+^${}()|[\]\\]/g, '\\$&');
  }
  return new RegExp(`^${re}$`);
}
export const matches = (lesson, path) => lesson.files.some((g) => globRe(g).test(path));
export const slice = (lessons, paths) => lessons.filter((l) => paths.some((p) => matches(l, p)));

// A check is "none: reason" or a repository path, optionally with "::" and what in it holds the rule.
export function checkPath(lesson) {
  if (/^none\b/.test(lesson.check)) return null;
  return lesson.check.split('::')[0].trim();
}

export function indexText(lessons) {
  const lines = lessons.map((l) => `- **${l.kind}**: ${l.rule} ([${l.path.split('/').pop().replace(/\.md$/, '')}](${l.path.replace(/^docs\/solutions\//, '')}))${checkPath(l) ? '' : ' *(no automatic check yet)*'}`);
  return `# Lessons index\n\nGenerated by \`node tools/lessons/index.mjs\` from the files in this folder: one line per solved problem. It is not loaded at session start. For a task, run \`node tools/lessons/slice.mjs <paths>\` and paste what it prints into the task.\n\n${lines.join('\n')}\n`;
}

export function sliceText(lessons) {
  if (!lessons.length) return '';
  return ['Rules from past mistakes that concern these files (docs/solutions):',
    ...lessons.map((l) => `- ${l.rule} [${l.kind}; check: ${l.check}; ${l.path}]`)].join('\n');
}
